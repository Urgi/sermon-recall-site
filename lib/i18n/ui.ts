const TABLES: Record<AppLanguage, Record<UiKey, string>> = { en: EN, es: ES, fr: FR };

function interpolate(template: string, vars?: UiVars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}

export function translateUi(language: unknown, key: UiKey, vars?: UiVars): string {
  const lang = normalizeAppLanguage(language);
  return interpolate(TABLES[lang][key] ?? EN[key], vars);
}

/** Language of the signed-in or remembered visitor; set by LanguageProvider for non-React helpers. */
let activeLanguage: AppLanguage = 'en';

export function setActiveUiLanguage(language: unknown): void {
  activeLanguage = normalizeAppLanguage(language);
}

export function getActiveUiLanguage(): AppLanguage {
  return activeLanguage;
}

/** Translate with the language the provider last announced (for lib helpers that return user-facing text). */
export function tr(key: UiKey, vars?: UiVars): string {
  return translateUi(activeLanguage, key, vars);
}

